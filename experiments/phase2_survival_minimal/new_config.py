def _expand_grid(grid, name="candidate"):
    """Return a list of parameter dictionaries from a compact grid spec."""
    full_grid = {
        "perception_radius": [DEFAULT_PERCEPTION_RADIUS],
        **grid,
        "care_weight": [BASELINE_GENOME_WEIGHTS["care_weight"]],
        "forage_weight": [BASELINE_GENOME_WEIGHTS["forage_weight"]],
        "self_weight": [BASELINE_GENOME_WEIGHTS["self_weight"]],
    }

    keys = list(full_grid.keys())
    configs = []

    for values in product(*[full_grid[k] for k in keys]):
        params = dict(zip(keys, values))
        params["name"] = name
        configs.append(params)

    return configs


def candidate_configs(mode="sweep"):
    """
    Generate candidate parameter sets for Phase 2.

    mode="single":
        Run one provisional anchor configuration for detailed diagnostics.

    mode="sweep":
        Run the roadmap validation grid:
            init_food × eat_gain × move_cost
        Final HARSH / BALANCED / EASY regimes must be selected from this grid.

    mode="pipeline":
        Run a denser exploratory grid when more resolution is needed.
    """
    if mode == "single":
        return [dict(SINGLE_CONFIG)]

    if mode == "pipeline":
        return _expand_grid(PIPELINE_GRID, name="candidate")

    return _expand_grid(SWEEP_GRID, name="candidate")


