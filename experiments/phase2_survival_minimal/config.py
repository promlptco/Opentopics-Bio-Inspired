# ============================================================
# Candidate grid for run.py baseline selection
# ============================================================

def candidate_configs(mode="sweep"):
    """
    Generate candidate parameter sets for run.py.

    mode="single":
        Runs one hand-picked configuration for detailed diagnostic plots.

    mode="sweep":
        11-point init_food grid (35–60). Covers the balanced→easy range.

    mode="pipeline":
        Not used — pipeline mode builds its sweep grid dynamically from
        the OVAT-detected balanced baseline via _pipeline_sweep_configs().

    Note:
        BASELINE_GENOME_WEIGHTS are fixed here. Phase 2 is not evolving
        weights yet; it only validates the ecological survival baseline
        under neutral FORAGE/SELF weighting.
    """
    if mode == "single":
        return [
            {
                "perception_radius": DEFAULT_PERCEPTION_RADIUS,
                "hunger_rate": 1 / 35,   # locked by starvation constraint
                "move_cost": 0.001,
                "eat_gain": 0.25,        # root Config default for locked hunger_rate
                "init_food": 90,         # 50x50 grid, 12 mothers, initial_energy=1.0
                "rest_recovery": 0.005,
                **BASELINE_GENOME_WEIGHTS,
                "name": "single_test",
            }
        ]

    # fmt: off
    _GRIDS = {
        "sweep": {
            "hunger_rate":    [1 / 35],  # locked — not swept
            "move_cost":      [0.001],
            "eat_gain":       [0.25],
            # init_food: shifted ~15% down vs 0.75 baseline (easier start = lower cliff)
            "init_food":      [55, 65, 75, 85, 95, 100, 110, 120, 135, 150, 165],
            "rest_recovery":  [0.005],
        },
        "pipeline": {
            # hunger_rate removed — locked at 1/35 by starvation constraint.
            # 4/5/6/4 = 480 configs.
            # init_food shifted ~15% down vs 0.75 baseline.
            "move_cost":     [0.0005, 0.001, 0.003, 0.006],
            "eat_gain":      [0.12, 0.18, 0.25, 0.32, 0.42],
            "init_food":     [40, 65, 100, 140, 175, 220],
            "rest_recovery": [0.005, 0.02, 0.05, 0.09],
        },
    }
    # fmt: on

    param_grid = _GRIDS.get(mode, _GRIDS["sweep"])

    grid = {
        "perception_radius": [DEFAULT_PERCEPTION_RADIUS],
        **param_grid,
        "care_weight":   [BASELINE_GENOME_WEIGHTS["care_weight"]],
        "forage_weight": [BASELINE_GENOME_WEIGHTS["forage_weight"]],
        "self_weight":   [BASELINE_GENOME_WEIGHTS["self_weight"]],
    }

    keys = list(grid.keys())
    configs = []

    for values in product(*[grid[k] for k in keys]):
        params = dict(zip(keys, values))
        params["name"] = "candidate"
        configs.append(params)

    return configs